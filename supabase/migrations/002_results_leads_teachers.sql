-- ============================================================
-- 002_results_leads_teachers.sql — Results, teachers, lead forms, mock scores
-- Run this whole file once in Supabase -> SQL Editor -> New query -> Run,
-- BEFORE pushing the new site code.
-- Safe to run more than once (every step uses "if not exists").
-- Nothing is deleted: date of birth and exam format columns stay as they are.
-- New tables get Row Level Security with no policies, so Supabase's public
-- API cannot read them; the Django backend connects directly and is unaffected.
-- ============================================================

begin;

-- 1. Lead forms: where the lead came from, preferred time, comment, staff note
alter table trial_registrations add column if not exists source text;
alter table trial_registrations add column if not exists preferred_time text;
alter table trial_registrations add column if not exists comment text;
alter table trial_registrations add column if not exists staff_note text;

-- 2. Mock exam result per registration (entered by staff); overall is calculated by Django
alter table exam_registrations add column if not exists listening numeric(3,1);
alter table exam_registrations add column if not exists reading numeric(3,1);
alter table exam_registrations add column if not exists writing numeric(3,1);
alter table exam_registrations add column if not exists speaking numeric(3,1);
alter table exam_registrations add column if not exists overall numeric(3,1);
alter table exam_registrations add column if not exists attended boolean;

-- 3. Student results for the website (hidden until is_published)
create table if not exists student_results (
  id bigint generated by default as identity primary key,
  image bytea,
  content_type text not null default 'image/jpeg',
  width integer not null default 0,
  height integer not null default 0,
  updated_at timestamptz not null default now(),
  first_name text not null,
  last_name_initial text not null default '',
  listening numeric(3,1) not null,
  reading numeric(3,1) not null,
  writing numeric(3,1) not null,
  speaking numeric(3,1) not null,
  overall numeric(3,1) not null,
  course text not null default 'ielts',
  exam_date date,
  is_published boolean not null default false,
  position integer not null default 0,
  created_at timestamptz not null default now()
);
alter table student_results enable row level security;

-- 4. Teachers for the website (hidden until is_published)
create table if not exists teachers (
  id bigint generated by default as identity primary key,
  image bytea,
  content_type text not null default 'image/jpeg',
  width integer not null default 0,
  height integer not null default 0,
  updated_at timestamptz not null default now(),
  name text not null,
  role text not null default '',
  ielts_band numeric(3,1),
  experience_years integer,
  tags text not null default '',
  is_published boolean not null default false,
  position integer not null default 0,
  created_at timestamptz not null default now()
);
alter table teachers enable row level security;

commit;
