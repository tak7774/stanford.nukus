-- ============================================================
-- 004_analytics_students_news.sql — Analytics, student accounts on mock
-- registrations, published results, and News with photos/events
-- Run this whole file once in Supabase -> SQL Editor -> New query -> Run,
-- BEFORE pushing the new site code.
-- Safe to run more than once. Nothing is deleted.
-- The gallery table (gallery_photos) is left as it is; the site no longer uses it.
-- ============================================================

begin;

-- 1. Page views for the Analytics page (no IP address, no user agent, no personal data)
create table if not exists analytics_pageviews (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  path text not null,
  visitor_id uuid not null,
  referrer text not null default '',
  device text not null default 'desktop'
);
create index if not exists analytics_pageviews_created_idx on analytics_pageviews (created_at);
alter table analytics_pageviews enable row level security;
revoke all on analytics_pageviews from anon, authenticated;

-- 2. Mock exam registrations: link to the student's portal account, and the "published" mark
alter table exam_registrations add column if not exists student_id bigint references portal_profile(id) on delete set null;
create index if not exists exam_registrations_student_idx on exam_registrations (student_id);
alter table exam_registrations add column if not exists results_published_by text;
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'exam_registrations' and column_name = 'results_published_at'
  ) then
    alter table exam_registrations add column results_published_at timestamptz;
    -- Results that staff already entered were already visible through the ticket lookup,
    -- so they stay visible: mark them as published (this runs only the first time).
    update exam_registrations
       set results_published_at = now(), results_published_by = 'before-publish-feature'
     where overall is not null;
  end if;
end $$;

-- 3. News become a full events manager: photo, kind, date, place, hide/show
alter table news add column if not exists image bytea;
alter table news add column if not exists content_type text not null default 'image/jpeg';
alter table news add column if not exists width integer not null default 0;
alter table news add column if not exists height integer not null default 0;
alter table news add column if not exists updated_at timestamptz not null default now();
alter table news add column if not exists kind text not null default 'news';
alter table news add column if not exists event_date timestamptz;
alter table news add column if not exists location text not null default '';
alter table news add column if not exists is_published boolean not null default true;

commit;
